// The release signing key is supplied by the GitHub workflow (repository secrets).
// Without it (e.g. a local build), the release APK is signed with the debug key.
val signingKeystore: String? = System.getenv("SIGNING_KEYSTORE_PATH")
val buildNumber: Int = (System.getenv("GITHUB_RUN_NUMBER") ?: "1").toInt()

