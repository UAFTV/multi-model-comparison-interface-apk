package com.uaftv.multimodelcomparison

import android.os.Bundle
import android.widget.Button
import android.widget.EditText
import android.widget.TextView
import androidx.appcompat.app.AppCompatActivity

class MainActivity : AppCompatActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_main)

        val promptInput = findViewById<EditText>(R.id.promptInput)
        val compareButton = findViewById<Button>(R.id.compareButton)

        val modelOneOutput = findViewById<TextView>(R.id.modelOneOutput)
        val modelTwoOutput = findViewById<TextView>(R.id.modelTwoOutput)
        val modelThreeOutput = findViewById<TextView>(R.id.modelThreeOutput)

        compareButton.setOnClickListener {
            val prompt = promptInput.text.toString().trim()
            if (prompt.isEmpty()) {
                promptInput.error = "Enter a prompt to compare model responses"
                return@setOnClickListener
            }

            modelOneOutput.text = "Claude Sonnet: $prompt\n\nThis response stays concise, structured, and practical while addressing the task directly."
            modelTwoOutput.text = "GPT-4o: $prompt\n\nThis version provides a balanced answer with broader context and a polished final summary."
            modelThreeOutput.text = "Gemini 1.5 Pro: $prompt\n\nThis output emphasizes synthesis, examples, and a richer layer of context."
        }
    }
}
